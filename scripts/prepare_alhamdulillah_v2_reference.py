"""Prepare the measured, reference-only workspace for Alhamdulillah V2.

This script does not create printable artwork or modify the preserved V1 CDR.
Run it first without corner measurements to obtain a normalized PNG/template,
then rerun into a new output directory with the completed measurement JSON.
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from corel_operator.reference_recreation import (  # noqa: E402
    ReferencePreparationError,
    prepare_a4_reference_workspace,
)


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Create a non-overwriting V2 reference workspace and, when measured corners are "
            "provided, rectify the photographed page to exact A4 landscape geometry."
        )
    )
    parser.add_argument("--source", type=Path, required=True, help="Local source photograph")
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help="New workspace directory (must not already exist)",
    )
    parser.add_argument(
        "--corner-measurements",
        type=Path,
        default=None,
        help="Completed a4-corner-measurements-v1 JSON generated by the first run",
    )
    parser.add_argument(
        "--rotation",
        default="counterclockwise_90",
        choices=("none", "clockwise_90", "counterclockwise_90", "180"),
        help="Rotation applied after EXIF normalization (the supplied photo requires CCW by default)",
    )
    return parser


def main() -> int:
    args = _parser().parse_args()
    output = args.output_dir or (
        ROOT / "output" / f"alhamdulillah_a4_vector_v2_{datetime.now():%Y%m%d_%H%M%S}"
    )
    try:
        manifest = prepare_a4_reference_workspace(
            args.source,
            output,
            rotation=args.rotation,
            corner_measurements_path=args.corner_measurements,
            project_name="Alhamdulillah A4 Vector Recreation V2",
        )
    except ReferencePreparationError as exc:
        print(json.dumps({"ok": False, "error": str(exc)}, indent=2), file=sys.stderr)
        return 2

    artifacts = manifest["artifacts"]
    print(
        json.dumps(
            {
                "ok": True,
                "status": manifest["status"],
                "workspace": str(Path(output).expanduser().resolve()),
                "source_sha256": manifest["source_preflight"]["sha256"],
                "rotated_corner_marking_image": artifacts["rotated_corner_marking_image"],
                "corner_measurement_template": artifacts["corner_measurement_template"],
                "rectified_reference": artifacts["rectified_reference"],
                "measurement_json": artifacts["measurement_json"],
                "next_gate": manifest["next_gate"],
            },
            indent=2,
            ensure_ascii=False,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
